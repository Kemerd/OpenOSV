bool driverPresent() noexcept {
#if !defined(_WIN32)
    // CUDA render is an NVIDIA-on-Windows path here; a Mac has no driver.
    return false;
#else
    // Already in the process: the host (Resolve on an NVIDIA machine) loaded
    // it, which is the case that matters - a CUDA render cannot happen
    // without it.
    if (::GetModuleHandleW(L"nvcuda.dll")) {
        return true;
    }
    // Otherwise look for it where the driver installs it, WITHOUT loading
    // anything from the plug-in folder or the host's directory.
    HMODULE probe = ::LoadLibraryExW(L"nvcuda.dll", nullptr, LOAD_LIBRARY_SEARCH_SYSTEM32);
    if (!probe) {
        return false;
    }
    // Keep it loaded: the delay-load stub will bind to this very module on
    // the first driver call, and unloading it now would only make that call
    // load it again.
    return true;
#endif
}

