struct Instance {
    /// Magic word so a corrupted or already-disposed pointer is detected
    /// rather than dereferenced.
    static constexpr std::uint32_t kMagic = 0x4F534756u;  // 'OSGV'
    std::uint32_t magic = kMagic;

    piSuitesPtr suites = nullptr;
    SPBasicSuite* basic = nullptr;

    // Suites.  Raw pointers with explicit releases in the destructor: the
    // RAII SuiteHandle in plugins/common is typed for the importer's set and
    // these are only ever held by one object with a well defined lifetime.
    const PrSDKGPUDeviceSuite* gpu = nullptr;
    const PrSDKPPixSuite* ppix = nullptr;
    const PrSDKVideoSegmentSuite* segment = nullptr;
    int segmentVersion = 0;
    const PrSDKSequenceInfoSuite* sequence = nullptr;
    int sequenceVersion = 0;

    csSDK_uint32 deviceIndex = 0;
    PrTimelineID timelineId = 0;
    csSDK_int32 nodeId = 0;

    CUcontext context = nullptr;
    CUstream stream = nullptr;
    CUfunction kernel = nullptr;

    /// AE index -> host GetParam index, discovered once in CreateInstance by
    /// probeParams().  Constructed with the static mapping so every read is
    /// well defined even if the probe never runs (no suite, a host that
    /// refuses GetParamCount, an exception on the way in).
    HostParamMap paramMap{};

    /// False until probeParams() has positively identified the host's index
    /// space.  The probe reads parameters through GetParam, which fails
    /// intermittently on a freshly created node, so a single failed attempt
    /// at CreateInstance must not condemn the instance to the static mapping
    /// for its whole life: Render retries while this is false.  Rendering a
    /// frame proves the node is ready, which is exactly when a retry works.
    bool paramMapProbed = false;

    /// [WP-CAMERA] How this host numbers popup entries on the GPU side
    /// (PopupBase in ReframeParams.h), learned from the values readSettings()
    /// sees: Premiere 26.2.2 counts from 0, After Effects and the mock host
    /// from 1.  Atomic because Render may run on several threads for one
    /// instance; the value only ever moves from Unknown to a settled base.
    /// Mutable because the readers take the instance const: learning the
    /// numbering is a cache of what the host says, not a change of state.
    mutable std::atomic<int> popupBase{static_cast<int>(PopupBase::Unknown)};

    // ---- the direct path (DirectPath.h) ---------------------------------
    /// The media file and owning clip node this instance renders; the node
    /// is acquired and released in DisposeInstance.
    osv::reframe::direct::SourceBinding source;
    /// OSV_TRANSFER_* of the sequence's working colour space, -1 when the
    /// direct path cannot produce it.
    int directTransfer = -1;
    /// Set after a failure that will not go away by itself (the file is not
    /// one the engine can open, the view cannot be expressed): the instance
    /// then stays on the equirect path instead of paying for the attempt on
    /// every frame.  A transient failure (a decode hiccup) does not set it.
    bool directDisabled = false;
    /// Failures logged so far for this instance (bounded, see render()).
    int directFailures = 0;

    Instance() noexcept { paramMap.setStatic(); }

    [[nodiscard]] bool alive() const noexcept { return magic == kMagic; }
};

/// Acquire a suite, returning nullptr instead of throwing.
template <class SuiteT>
const SuiteT* acquire(SPBasicSuite* basic, const char* name, int version) noexcept {
    if (!basic || !basic->AcquireSuite || !name) {
        return nullptr;
    }
    const void* suite = nullptr;
    if (basic->AcquireSuite(name, version, &suite) != kSPNoError || !suite) {
        return nullptr;
    }
    return static_cast<const SuiteT*>(suite);
}

/// Acquire the first version of a suite the host provides.  Used for the
/// Video Segment Suite (9 -> 8 -> 7 -> 6; only GetParam and GetNodeProperty
/// are used and both are v4 members) and the Sequence Info Suite.
template <class SuiteT>
const SuiteT* acquireFirst(SPBasicSuite* basic, const char* name, std::initializer_list<int> versions,
                           int* outVersion) noexcept {
    for (const int v : versions) {
        if (const SuiteT* suite = acquire<SuiteT>(basic, name, v)) {
            if (outVersion) {
                *outVersion = v;
            }
            return suite;
        }
    }
    if (outVersion) {
        *outVersion = 0;
    }
    return nullptr;
}

/// Release a suite if it was acquired.
void releaseSuite(SPBasicSuite* basic, const char* name, int version) noexcept {
    if (basic && basic->ReleaseSuite && name && version > 0) {
        basic->ReleaseSuite(name, version);
    }
}

