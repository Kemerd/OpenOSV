// ===========================================================================
//  The exported entry point
//
//  Startup fills the function table and the match name; shutdown frees the
//  per-device modules.  ioIndex would be incremented if this module held
//  more than one GPU filter - it holds exactly one, so it is left alone and
//  a non-zero index is refused.
// ===========================================================================
extern "C" __declspec(dllexport) prSuiteError xGPUFilterEntry(csSDK_uint32 inHostInterfaceVersion,
                                                              csSDK_int32* ioIndex, prBool inStartup,
                                                              piSuitesPtr piSuites, PrGPUFilter* outFilter,
                                                              PrGPUFilterInfo* outFilterInfo) {
    try {
        // The host tells us which interface it speaks; we implement 2 and
        // nothing older, so an older host is declined cleanly.
        if (inHostInterfaceVersion < PrSDKGPUFilterInterfaceVersion2) {
            return suiteError_InvalidParms;
        }
        if (!ioIndex) {
            return suiteError_InvalidParms;
        }
        if (*ioIndex != 0) {
            // Exactly one GPU filter in this module.
            return suiteError_InvalidParms;
        }

        if (!inStartup) {
            // Shutdown: the contexts are still alive here, which is the only
            // safe moment to unload the modules.
            releaseKernels();
            PluginLog::info("reframe/gpu: shutdown");
            return suiteError_NoError;
        }

        if (!outFilter || !outFilterInfo) {
            return suiteError_InvalidParms;
        }

        // The log file is opened here rather than in DllMain: DllMain runs
        // under the loader lock and must not touch the file system.
        osv::premiere::PluginLog::init(L"Open360Reframe");

        outFilter->CreateInstance = &createInstance;
        outFilter->DisposeInstance = &disposeInstance;
        outFilter->GetFrameDependencies = &getFrameDependencies;
        outFilter->Precompute = &precompute;
        outFilter->Render = &render;

        outFilterInfo->outInterfaceVersion = PrSDKGPUFilterInterfaceVersion2;
        // Leaving outMatchName null would make the host use the module's
        // PiPL match name, which is the same string - but being explicit
        // means the binding cannot depend on the resource being found, and
        // the test can read the value back.
        outFilterInfo->outMatchName = PrSDKString();
        if (piSuites && piSuites->utilFuncs && piSuites->utilFuncs->getSPBasicSuite) {
            SPBasicSuite* basic = piSuites->utilFuncs->getSPBasicSuite();
            if (const PrSDKStringSuite* strings =
                    acquire<PrSDKStringSuite>(basic, kPrSDKStringSuite, kPrSDKStringSuiteVersion)) {
                if (strings->AllocateFromUTF8) {
                    // prUTF8Char is an unsigned char typedef; the literal is
                    // pure ASCII so the reinterpretation is exact.
                    strings->AllocateFromUTF8(reinterpret_cast<const prUTF8Char*>(OSV_REFRAME_MATCH_NAME),
                                              &outFilterInfo->outMatchName);
                }
                releaseSuite(basic, kPrSDKStringSuite, kPrSDKStringSuiteVersion);
            }
        }

        PluginLog::info("reframe/gpu: startup, host interface version {}", inHostInterfaceVersion);
        return suiteError_NoError;
    } catch (...) {
        return suiteError_Fail;
    }
}
