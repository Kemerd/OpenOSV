prSuiteError createInstance(PrGPUFilterInstance* io) noexcept {
    try {
        if (!io || !io->piSuites || !io->piSuites->utilFuncs || !io->piSuites->utilFuncs->getSPBasicSuite) {
            return suiteError_InvalidParms;
        }
        SPBasicSuite* basic = io->piSuites->utilFuncs->getSPBasicSuite();
        if (!basic) {
            return suiteError_InvalidParms;
        }

        Instance* inst = new (std::nothrow) Instance();
        if (!inst) {
            return suiteError_OutOfMemory;
        }
        inst->suites = io->piSuites;
        inst->basic = basic;
        inst->deviceIndex = io->inDeviceIndex;
        inst->timelineId = io->inTimelineID;
        inst->nodeId = io->inNodeID;

        // ---- the device -------------------------------------------------
        inst->gpu = acquire<PrSDKGPUDeviceSuite>(basic, kPrSDKGPUDeviceSuite, kPrSDKGPUDeviceSuiteVersion);
        if (!inst->gpu || !inst->gpu->GetDeviceInfo) {
            PluginLog::warn("reframe/gpu: no GPU Device Suite; rendering in software");
            delete inst;
            return suiteError_Fail;
        }

        PrGPUDeviceInfo info{};
        if (inst->gpu->GetDeviceInfo(kPrSDKGPUDeviceSuiteVersion, io->inDeviceIndex, &info) != suiteError_NoError) {
            PluginLog::warn("reframe/gpu: GetDeviceInfo failed for device {}", io->inDeviceIndex);
            releaseSuite(basic, kPrSDKGPUDeviceSuite, kPrSDKGPUDeviceSuiteVersion);
            delete inst;
            return suiteError_Fail;
        }

        // CUDA only.  OpenCL was dropped by Premiere in 15.4, Metal is Mac
        // and DirectX is still unreleased for third parties; returning an
        // error here makes the host render this node in software, which is
        // exactly the documented fallback (PrSDKGPUFilter.h:167-170).
        if (info.outDeviceFramework != PrGPUDeviceFramework_CUDA) {
            PluginLog::info("reframe/gpu: device {} is not CUDA (framework {}); using the CPU path",
                            io->inDeviceIndex, static_cast<int>(info.outDeviceFramework));
            releaseSuite(basic, kPrSDKGPUDeviceSuite, kPrSDKGPUDeviceSuiteVersion);
            delete inst;
            return suiteError_Fail;
        }
        if (!info.outMeetsMinimumRequirementsForAcceleration) {
            PluginLog::info("reframe/gpu: device {} does not meet the acceleration minimum; using the CPU path",
                            io->inDeviceIndex);
            releaseSuite(basic, kPrSDKGPUDeviceSuite, kPrSDKGPUDeviceSuiteVersion);
            delete inst;
            return suiteError_Fail;
        }

        inst->context = static_cast<CUcontext>(info.outContextHandle);
        inst->stream = static_cast<CUstream>(info.outCommandQueueHandle);
        if (!inst->context) {
            PluginLog::warn("reframe/gpu: the host reported a CUDA device with no context");
            releaseSuite(basic, kPrSDKGPUDeviceSuite, kPrSDKGPUDeviceSuiteVersion);
            delete inst;
            return suiteError_Fail;
        }

        // ---- the kernel -------------------------------------------------
        inst->kernel = acquireKernel(io->inDeviceIndex, inst->context);
        if (!inst->kernel) {
            releaseSuite(basic, kPrSDKGPUDeviceSuite, kPrSDKGPUDeviceSuiteVersion);
            delete inst;
            return suiteError_Fail;
        }

        // ---- the remaining suites ---------------------------------------
        inst->ppix = acquire<PrSDKPPixSuite>(basic, kPrSDKPPixSuite, kPrSDKPPixSuiteVersion);
        if (!inst->ppix) {
            PluginLog::warn("reframe/gpu: no PPix Suite; rendering in software");
            releaseSuite(basic, kPrSDKGPUDeviceSuite, kPrSDKGPUDeviceSuiteVersion);
            delete inst;
            return suiteError_Fail;
        }

        // Only GetParam is used and it exists since v4; acquire the newest
        // the host has so a future host does not silently give us an old
        // table, but never fail over a missing high version.
        inst->segment = acquireFirst<PrSDKVideoSegmentSuite>(
            basic, kPrSDKVideoSegmentSuite,
            {kPrSDKVideoSegmentSuiteVersion9, kPrSDKVideoSegmentSuiteVersion8, kPrSDKVideoSegmentSuiteVersion7,
             kPrSDKVideoSegmentSuiteVersion6},
            &inst->segmentVersion);
        if (!inst->segment) {
            PluginLog::warn("reframe/gpu: no Video Segment Suite; parameters cannot be read, rendering in software");
            releaseSuite(basic, kPrSDKPPixSuite, kPrSDKPPixSuiteVersion);
            releaseSuite(basic, kPrSDKGPUDeviceSuite, kPrSDKGPUDeviceSuiteVersion);
            delete inst;
            return suiteError_Fail;
        }

        // Optional: without it "Match Sequence" falls back to 16:9.
        inst->sequence = acquireFirst<PrSDKSequenceInfoSuite>(basic, kPrSDKSequenceInfoSuite,
                                                              {kPrSDKSequenceInfoSuiteVersion, 8, 7, 6, 5},
                                                              &inst->sequenceVersion);

        // Discover the host's parameter index space, once per instance.
        //
        // gpuParamIndex() encodes the documented rule, "AE index - 1"
        // (PrGPUFilterModule.h:153), which assumes the host's GetParam index
        // space is the list After Effects built, group markers included.
        // Premiere Pro 26.2 disproves that: this effect adds 15 parameters
        // (11 controls + 4 group markers) and GetParamCount answers 8 - the
        // markers are dropped AND the three controls inside the collapsed
        // "Source" group are not exposed.  Under the static rule every read
        // past the first group landed on a neighbouring control, FOV came
        // back as garbage and the render bailed out entirely.
        //
        // probeParams() asks the host what it really has and identifies each
        // control by its PrParam type, so the mapping is measured rather than
        // assumed.  It is deliberately non-fatal: a host it cannot identify
        // leaves the static mapping in place, which is exactly the behaviour
        // that existed before, and says so in the log.
        probeParams(*inst);

        io->ioPrivatePluginData = inst;
        // Reframing a 6K equirect into an HD frame is a couple of samples
        // per output pixel on the GPU; it plays back in real time.
        io->outIsRealtime = kPrTrue;

        PluginLog::info("reframe/gpu: instance on device {} (video segment v{}, sequence info v{})",
                        io->inDeviceIndex, inst->segmentVersion, inst->sequenceVersion);
        return suiteError_NoError;
    } catch (...) {
        // An exception must never cross back into Premiere's C stack.
        return suiteError_Fail;
    }
}

prSuiteError disposeInstance(PrGPUFilterInstance* io) noexcept {
    try {
        if (!io) {
            return suiteError_InvalidParms;
        }
        Instance* inst = static_cast<Instance*>(io->ioPrivatePluginData);
        io->ioPrivatePluginData = nullptr;
        if (!inst) {
            return suiteError_NoError;  // never created, or disposed twice
        }
        if (!inst->alive()) {
            PluginLog::error("reframe/gpu: DisposeInstance on a corrupt instance pointer");
            return suiteError_InvalidParms;
        }

        // Release exactly what was acquired, in reverse order.  The module
        // cache is NOT touched here: other instances on the same device
        // still use it and it is freed in the entry point's shutdown.
        SPBasicSuite* basic = inst->basic;
        if (inst->sequence) {
            releaseSuite(basic, kPrSDKSequenceInfoSuite, inst->sequenceVersion);
        }
        if (inst->segment) {
            releaseSuite(basic, kPrSDKVideoSegmentSuite, inst->segmentVersion);
        }
        if (inst->ppix) {
            releaseSuite(basic, kPrSDKPPixSuite, kPrSDKPPixSuiteVersion);
        }
        if (inst->gpu) {
            releaseSuite(basic, kPrSDKGPUDeviceSuite, kPrSDKGPUDeviceSuiteVersion);
        }
        inst->magic = 0;
        delete inst;
        return suiteError_NoError;
    } catch (...) {
        return suiteError_Fail;
    }
}

