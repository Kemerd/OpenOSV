// ===========================================================================
//  The embedded fatbin
//
//  Generated by cmake/EmbedKernelScript.cmake from the fatbin nvcc produced
//  out of ReframeKernel.cu.  The generated translation unit defines these at
//  global scope with ordinary C++ linkage, so the declarations here are at
//  global scope too (an anonymous namespace would give them internal linkage
//  and the link would fail with an unresolved symbol).
// ===========================================================================
extern const unsigned char kOsvReframeFatbin[];
extern const std::size_t kOsvReframeFatbin_size;

