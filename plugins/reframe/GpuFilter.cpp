/// Turn a CUresult into something a log line can carry.
std::string cudaMessage(const char* what, CUresult result) {
    const char* name = nullptr;
    const char* text = nullptr;
    cuGetErrorName(result, &name);
    cuGetErrorString(result, &text);
    std::string s(what ? what : "cuda");
    s += ": ";
    s += name ? name : "CUDA_ERROR_UNKNOWN";
    if (text) {
        s += " (";
        s += text;
        s += ")";
    }
    return s;
}

/// RAII push/pop of a CUcontext.  Pushing the context that is already
/// current is legal and cheap; popping in the destructor guarantees the
/// thread is left exactly as Premiere handed it to us even on an early
/// return or an exception.
class ContextScope {
public:
    explicit ContextScope(CUcontext context) noexcept {
        if (!context) {
            return;
        }
        m_pushed = (cuCtxPushCurrent(context) == CUDA_SUCCESS);
    }
    ~ContextScope() {
        if (m_pushed) {
            CUcontext popped = nullptr;
            cuCtxPopCurrent(&popped);
        }
    }
    ContextScope(const ContextScope&) = delete;
    ContextScope& operator=(const ContextScope&) = delete;

    [[nodiscard]] bool ok() const noexcept { return m_pushed; }

private:
    bool m_pushed = false;
};

// ===========================================================================
//  Per-device module cache
//
//  cuModuleLoadFatBinary is expensive (it JITs for the device if no matching
//  cubin is present) and CreateInstance runs on every parameter change, so
//  one module per device is loaded once and kept until Shutdown.  The table
//  is keyed by the CUcontext as well as the device index: a host that
//  recreated its context would otherwise hand us a module belonging to a
//  destroyed context, which is undefined behaviour.
// ===========================================================================
struct DeviceModule {
    CUcontext context = nullptr;
    CUmodule module = nullptr;
    CUfunction kernel = nullptr;
    /// The direct path's fused fisheye -> view kernel, from the same fatbin.
    /// Null only if this build's fatbin lacks it; the equirect path is then
    /// the only one, exactly as before the direct path existed.
    CUfunction direct = nullptr;
    bool valid = false;
};

std::mutex g_moduleMutex;
DeviceModule g_modules[kMaxDevices];

/// Load (or fetch) the module for a device.  Caller must NOT hold the
/// context pushed - this function pushes it itself.  Returns nullptr on
/// failure, having logged the reason.
CUfunction acquireKernel(csSDK_uint32 deviceIndex, CUcontext context) noexcept {
    if (deviceIndex >= kMaxDevices || !context) {
        PluginLog::error("reframe/gpu: device index {} or context unusable", deviceIndex);
        return nullptr;
    }
    if (kOsvReframeFatbin_size == 0) {
        PluginLog::error("reframe/gpu: the embedded fatbin is empty - the build did not run nvcc");
        return nullptr;
    }

    std::lock_guard<std::mutex> lock(g_moduleMutex);
    DeviceModule& slot = g_modules[deviceIndex];
    if (slot.valid && slot.context == context && slot.kernel) {
        return slot.kernel;
    }

    // A stale entry (different context) is dropped without unloading: the
    // context it belonged to is gone, so cuModuleUnload would fail or worse.
    if (slot.valid && slot.context != context) {
        PluginLog::warn("reframe/gpu: device {} changed context, reloading the module", deviceIndex);
        slot = DeviceModule{};
    }

    ContextScope scope(context);
    if (!scope.ok()) {
        PluginLog::error("reframe/gpu: cuCtxPushCurrent failed for device {}", deviceIndex);
        return nullptr;
    }

    CUmodule module = nullptr;
    CUresult r = cuModuleLoadFatBinary(&module, kOsvReframeFatbin);
    if (r != CUDA_SUCCESS || !module) {
        PluginLog::error("reframe/gpu: {}", cudaMessage("cuModuleLoadFatBinary", r));
        return nullptr;
    }

    CUfunction kernel = nullptr;
    r = cuModuleGetFunction(&kernel, module, kKernelName);
    if (r != CUDA_SUCCESS || !kernel) {
        PluginLog::error("reframe/gpu: {}", cudaMessage("cuModuleGetFunction", r));
        cuModuleUnload(module);
        return nullptr;
    }

    // The fused kernel is optional: failing to find it only switches the
    // direct path off, never the effect.
    CUfunction direct = nullptr;
    r = cuModuleGetFunction(&direct, module, kDirectKernelName);
    if (r != CUDA_SUCCESS || !direct) {
        PluginLog::warn("reframe/gpu: the fused direct kernel is missing from the fatbin ({}); rendering from the "
                        "equirect only",
                        cudaMessage("cuModuleGetFunction", r));
        direct = nullptr;
    }

    slot.context = context;
    slot.module = module;
    slot.kernel = kernel;
    slot.direct = direct;
    slot.valid = true;
    PluginLog::info("reframe/gpu: loaded the reframe kernel on device {} ({} bytes of fatbin)", deviceIndex,
                    kOsvReframeFatbin_size);
    return kernel;
}

/// The fused direct kernel for a device and context, or null when the module
/// is not loaded for that context (acquireKernel() loads it) or lacks it.
CUfunction directKernelFor(csSDK_uint32 deviceIndex, CUcontext context) noexcept {
    if (deviceIndex >= kMaxDevices || !context) {
        return nullptr;
    }
    std::lock_guard<std::mutex> lock(g_moduleMutex);
    const DeviceModule& slot = g_modules[deviceIndex];
    return (slot.valid && slot.context == context) ? slot.direct : nullptr;
}

/// Unload every cached module.  Called from the entry point's shutdown
/// phase, which is the only moment the host guarantees the contexts are
/// still alive and no render is in flight.
void releaseKernels() noexcept {
    std::lock_guard<std::mutex> lock(g_moduleMutex);
    for (DeviceModule& slot : g_modules) {
        if (slot.valid && slot.module && slot.context) {
            ContextScope scope(slot.context);
            if (scope.ok()) {
                cuModuleUnload(slot.module);
            }
        }
        slot = DeviceModule{};
    }
}

// ===========================================================================
//  Per-instance state (PrGPUFilterInstance::ioPrivatePluginData)
