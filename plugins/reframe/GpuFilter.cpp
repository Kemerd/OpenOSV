/// One GetParam call.
///
/// `aeIndex` is the AE parameter index; the host index it maps to comes from
/// the instance's HostParamMap, which CreateInstance either probed from the
/// host or left at the static "AE index - 1" rule.  A control the host does
/// not expose maps to -1 and the read fails cleanly, so the caller uses that
/// control's default rather than a neighbour's value.
bool readParam(const Instance& inst, int aeIndex, PrTime time, PrParam* out) noexcept {
    if (!inst.segment || !inst.segment->GetParam || !out) {
        return false;
    }
    const int hostIndex = inst.paramMap[aeIndex];
    if (hostIndex < 0) {
        return false;
    }
    std::memset(out, 0, sizeof(*out));
    const prSuiteError err = inst.segment->GetParam(inst.nodeId, hostIndex, time, out);
    return err == suiteError_NoError;
}

/// Translate one PrParam variant into the dialect matchHostParams() speaks.
/// Anything we do not use maps to Unknown, which matches nothing.
[[nodiscard]] HostParamKind kindOf(const PrParam& p) noexcept {
    switch (p.mType) {
        case kPrParamType_Int32:   return HostParamKind::Int32;
        case kPrParamType_Float32: return HostParamKind::Float32;
        case kPrParamType_Float64: return HostParamKind::Float64;
        case kPrParamType_Bool:    return HostParamKind::Bool;
        default:                   return HostParamKind::Unknown;
    }
}

/// Discover the host's parameter index space, once per instance.
///
/// Asks GetParamCount how many entries there are, reads each one's TYPE at
/// time 0, and identifies the list as one of the two layouts Premiere has
/// been seen to use (matchVerbatimLayout() below, then matchHostParams()).
/// On a positive identification the instance's map is replaced; otherwise
/// the static map it was constructed with is kept.  Either way the function
/// is non-fatal - it only ever improves the mapping, never breaks it - and it
/// logs which of the two is in force so a log alone answers the question.
///
/// Cost: one GetParamCount plus at most kParamCount GetParam calls (a few
/// retries each for entries that do not answer), all at t = 0, on a code
/// path Premiere runs when an effect is applied or a parameter changes - not
/// per frame.
void probeParams(Instance& inst) noexcept;

// ---------------------------------------------------------------------------
//  The VERBATIM host layout
//
//  Premiere Pro 26.2.2 was seen to hand a GPU filter this effect's parameter
//  list exactly as After Effects built it, minus the input layer:
//
//      GetParamCount = 15 = OSV_REFRAME_PARAM_COUNT
//      [0]i32:0 [1]bool:0 [2]i32:3 [3]f32:0 [4]f32:0 [5]f32:0 [6]f64:120
//      [7]f64:15 [8]bool:0 [9]bool:0 [10]f32:0   (11..14 unreadable at t = 0)
//
//  i.e. host index = AE index - 1, and the four group markers (Camera start
//  and end, Source start and end) PRESENT, answering as Bool.  An older
//  session showed the same layout with the markers refusing to answer at
//  all.  This is the layout the static "AE index - 1" rule assumes, so the
//  static mapping was right - but the matcher only knew the COMPACT layout
//  (markers dropped, a collapsed group missing) and logged a false "types do
//  not match" error on every such host.  Worse, the old probe read only the
//  first kValueParamCount entries of a 15-entry list, and when the markers
//  refused to answer, the FOV/Distortion anchor "identified" that prefix at
//  a constant offset that is wrong past the first group marker: Source Roll
//  was read out of Source Pan's slot while Source Pan, Source Tilt, Smooth
//  Keyframes and Output Resolution were not read at all.
//
//  The expected layout is built from ReframeParams.h alone - every AE index
//  in kValueParamAeIndex carries kValueParamKind, every other index up to
//  kParamCount is a group marker - so a control appended there (a new id,
//  a new AE index, a new kind entry) is recognised here with no change to
//  this code.
// ---------------------------------------------------------------------------

/// The smallest number of value-carrying entries that must answer with the
/// expected type before a verbatim identification is believed.  Five is the
/// same bar the compact matcher's anchor applies: a list that answers less
/// than that is not identified but unreadable, so the static mapping (which
/// IS the verbatim mapping) stays in force, the log says so, and Render
/// retries the probe once the node answers.
constexpr int kVerbatimMinTypedValues = 5;

// The tables the verbatim layout is derived from must describe a list the
// host map can hold.  Checked at compile time so a table edit that breaks
// the invariant fails the build rather than the probe.
static_assert(kValueParamCount > 0 && kValueParamCount <= kParamCount,
              "ReframeParams.h: the value controls must be a subset of the AE parameter list");
static_assert(
    [] {
        for (int i = 0; i < kValueParamCount; ++i) {
            if (kValueParamAeIndex[i] < 1 || kValueParamAeIndex[i] > kParamCount) {
                return false;
            }
            for (int j = 0; j < i; ++j) {
                if (kValueParamAeIndex[j] == kValueParamAeIndex[i]) {
                    return false;
                }
            }
        }
        return true;
    }(),
    "ReframeParams.h: kValueParamAeIndex must name distinct AE indices in 1..kParamCount");

/// What the verbatim layout expects at host index `hostIndex`: the kind of
/// the value control whose AE index is hostIndex + 1, or `isMarker` = true
/// when that AE index belongs to no value control (a group start or end).
/// Returns false for an index outside the list.
[[nodiscard]] bool verbatimExpectation(int hostIndex, HostParamKind* kind, bool* isMarker) noexcept {
    if (!kind || !isMarker || hostIndex < 0 || hostIndex >= kParamCount) {
        return false;
    }
    const int aeIndex = hostIndex + 1;
    for (int i = 0; i < kValueParamCount; ++i) {
        if (kValueParamAeIndex[i] == aeIndex) {
            *kind = kValueParamKind[i];
            *isMarker = false;
            return true;
        }
    }
    *kind = HostParamKind::Unknown;
    *isMarker = true;
    return true;
}

/// Identify the host list as this effect's AE parameter list verbatim.
///
/// `kinds` holds what the host answered for indices 0 .. readCount-1
/// (Unknown for an entry that refused or carried a type we do not use) and
/// `hostCount` what GetParamCount said.  Rules, each one a guard against a
/// plausible-looking wrong answer:
///
///   1. the host must report exactly kParamCount entries - the one number
///      that separates this layout from the compact one (8 or 11 there);
///   2. every entry that DID answer must agree with its position: a value
///      control with its own kind, a group marker with Bool (Premiere's
///      answer for a marker) - one contradiction and the list is not ours;
///   3. an entry that did not answer contradicts nothing - Premiere 26.2.2
///      refuses the trailing entries of a freshly built node at t = 0 - but
///      it is not evidence either, so at least kVerbatimMinTypedValues value
///      controls must have answered with the right kind.
///
/// On success every value control is mapped to its position, INCLUDING the
/// ones that did not answer at t = 0: in this layout the index is known
/// from the list itself, not inferred from the answers, and a read that
/// fails at render time still falls back to the control's default in the
/// readers.  Group markers stay at -1 (they carry no value and are never
/// read).  On failure `outMap` is untouched.
[[nodiscard]] bool matchVerbatimLayout(const HostParamKind* kinds, int readCount, int hostCount,
                                       HostParamMap* outMap) noexcept {
    if (!kinds || !outMap || hostCount != kParamCount || readCount < 0 || readCount > kParamCount) {
        return false;
    }
    int typedValues = 0;
    for (int host = 0; host < readCount; ++host) {
        HostParamKind expected = HostParamKind::Unknown;
        bool isMarker = false;
        if (!verbatimExpectation(host, &expected, &isMarker)) {
            return false;
        }
        const HostParamKind got = kinds[host];
        if (got == HostParamKind::Unknown) {
            continue;  // rule 3: no answer, no contradiction, no evidence
        }
        if (isMarker) {
            if (got != HostParamKind::Bool) {
                return false;  // rule 2: a marker answering as a value
            }
            continue;
        }
        if (got != expected) {
            return false;  // rule 2: a value control of the wrong kind
        }
        ++typedValues;
    }
    if (typedValues < kVerbatimMinTypedValues) {
        return false;
    }

    // ---- positional map ------------------------------------------------------
    HostParamMap map{};
    for (int i = 0; i <= OSV_REFRAME_PARAM_COUNT; ++i) {
        map.hostIndex[i] = -1;
    }
    for (int i = 0; i < kValueParamCount; ++i) {
        const int aeIndex = kValueParamAeIndex[i];
        map.hostIndex[aeIndex] = gpuParamIndex(aeIndex);
    }
    map.probed = true;
    *outMap = map;
    return true;
}

// ===========================================================================
//  Source-graph probe (diagnostic, once per process)
//
//  Can the effect find the clip it is applied to?  If the effect node can
//  walk to its media node and read which file and which media time it is
//  rendering, the reframe can sample the two FISHEYES directly on the GPU -
//  one resampling instead of fisheye -> equirect -> view, and no 18 MP
//  equirect round trip through host memory at all.  The Video Segment Suite
//  documents the walk (operator -> owner clip node -> input media node ->
//  "MediaNode::MediaInstanceString" and friends) but not what the values
//  hold in practice, so the first instance in a process logs every property
//  it can reach.  It changes nothing about rendering.
// ===========================================================================

/// Collects IterateNodeProperties callbacks.  The callback's plug-in object
/// is a csSDK_int32 - too narrow for a pointer on 64-bit - so the
/// accumulator is thread-local; the iteration is synchronous on this thread.
thread_local std::string* t_propertySink = nullptr;

prSuiteError collectProperty(csSDK_int32, const char* key, const prUTF8Char* value) {
    if (!t_propertySink) {
        return suiteError_NoError;
    }
    std::string v = value ? reinterpret_cast<const char*>(value) : "<null>";
    // Values can be long XML blobs; the head is enough to identify them.
    constexpr std::size_t kMaxValue = 240;
    if (v.size() > kMaxValue) {
        v = v.substr(0, kMaxValue) + "...(" + std::to_string(v.size()) + " bytes)";
    }
    t_propertySink->append("\n    ").append(key ? key : "<null>").append(" = ").append(v);
    return suiteError_NoError;
}

/// Log one node's type and all of its properties.
void logNode(const PrSDKVideoSegmentSuite& s, csSDK_int32 node, const char* role) {
    char type[kMaxNodeTypeStringSize] = {};
    prPluginID hash{};
    csSDK_int32 flags = 0;
    if (s.GetNodeInfo) {
        (void)s.GetNodeInfo(node, type, &hash, &flags);
    }
    std::string props;
    if (s.IterateNodeProperties) {
        t_propertySink = &props;
        const prSuiteError err = s.IterateNodeProperties(node, &collectProperty, 0);
        t_propertySink = nullptr;
        if (err != suiteError_NoError) {
            props.append("\n    (IterateNodeProperties failed: ").append(std::to_string(err)).append(")");
        }
    }
    PluginLog::info("reframe/gpu/source: {} node {} type '{}' flags 0x{:x}{}", role, node, type,
                    static_cast<unsigned>(flags), props);
}

/// Log, once, whether the CUcontext Premiere hands GPU filters is its device's
/// PRIMARY context.  If it is, the importer's CUDA work (which runs on the
/// primary context through the runtime API) already shares an address space
/// with the effect, and one decoder + VRAM frame cache can serve both paths;
/// if not, device memory cannot cross between them and each needs its own.
///
/// cuDevicePrimaryCtxGetState is used first so the probe never CREATES a
/// primary context that was not already alive (that would cost VRAM); only
/// when one is active is it retained - briefly, to read its handle - and
/// released again.
void probeHostContext(CUcontext hostContext) noexcept {
    try {
        static std::atomic<bool> done{false};
        if (!hostContext || done.exchange(true)) {
            return;
        }
        ContextScope scope(hostContext);
        if (!scope.ok()) {
            return;
        }
        CUdevice device = 0;
        if (cuCtxGetDevice(&device) != CUDA_SUCCESS) {
            return;
        }
        unsigned int flags = 0;
        int active = 0;
        if (cuDevicePrimaryCtxGetState(device, &flags, &active) != CUDA_SUCCESS) {
            return;
        }
        unsigned int apiVersion = 0;
        (void)cuCtxGetApiVersion(hostContext, &apiVersion);
        if (!active) {
            PluginLog::info("reframe/gpu/source: host CUDA context {} on device {} (api {}); the device's primary "
                            "context is NOT active, so the host context is a private one",
                            static_cast<const void*>(hostContext), static_cast<int>(device), apiVersion);
            return;
        }
        CUcontext primary = nullptr;
        if (cuDevicePrimaryCtxRetain(&primary, device) != CUDA_SUCCESS) {
            return;
        }
        PluginLog::info("reframe/gpu/source: host CUDA context {} on device {} (api {}) {} the primary context {} "
                        "(flags 0x{:x})",
                        static_cast<const void*>(hostContext), static_cast<int>(device), apiVersion,
                        primary == hostContext ? "IS" : "is NOT", static_cast<const void*>(primary), flags);
        (void)cuDevicePrimaryCtxRelease(device);
    } catch (...) {
        // Diagnostics must never take the effect down.
    }
}

/// Log the sequence's working colour space - the space the frames an effect
/// receives, and must return, are expressed in.  A direct render from the
/// fisheyes bypasses Premiere's source -> working conversion, so it has to
/// produce this space itself: the SEI codes say which transfer and primaries,
/// and the graphics-white / tone-map / SDR-gamma settings say how Premiere
/// scales between HDR and SDR.  Diagnostic only.
void probeWorkingColorSpace(const Instance& inst) noexcept {
    try {
        // GetWorkingColorSpace and the three settings after it sit at the end
        // of the v9 function table; reading them from an older host's shorter
        // table would read past it.
        if (!inst.sequence || inst.sequenceVersion < 9 || !inst.sequence->GetWorkingColorSpace) {
            PluginLog::info("reframe/gpu/source: the Sequence Info Suite (v{}) cannot report the working colour space",
                            inst.sequenceVersion);
            return;
        }
        PrSDKColorSpaceID id{};
        const prSuiteError idErr = inst.sequence->GetWorkingColorSpace(inst.timelineId, &id);
        csSDK_uint32 white = 0;
        prBool toneMap = kPrFalse;
        csSDK_uint32 gamma = 0;
        const prSuiteError whiteErr =
            inst.sequence->GetGraphicsWhiteLuminance ? inst.sequence->GetGraphicsWhiteLuminance(inst.timelineId, &white)
                                                     : suiteError_NotImplemented;
        const prSuiteError toneErr =
            inst.sequence->GetAutoToneMapEnabled ? inst.sequence->GetAutoToneMapEnabled(inst.timelineId, &toneMap)
                                                 : suiteError_NotImplemented;
        const prSuiteError gammaErr = inst.sequence->GetSDRGamma ? inst.sequence->GetSDRGamma(inst.timelineId, &gamma)
                                                                 : suiteError_NotImplemented;

        // Resolve the opaque id through the Color Management Suite.
        PrSDKColorSpaceType type = kPrSDKColorSpaceType_Undefined;
        prSEIColorCodesRec sei;
        prSuiteError typeErr = suiteError_NotImplemented;
        prSuiteError seiErr = suiteError_NotImplemented;
        if (const PrSDKColorManagementSuite* cm = acquire<PrSDKColorManagementSuite>(
                inst.basic, kPrSDKColorManagementSuite, kPrSDKColorManagementSuiteVersion)) {
            if (idErr == suiteError_NoError && cm->GetColorSpaceTypeForColorSpace) {
                typeErr = cm->GetColorSpaceTypeForColorSpace(&id, &type);
            }
            if (idErr == suiteError_NoError && cm->GetSEIColorCodesForColorSpace) {
                seiErr = cm->GetSEIColorCodesForColorSpace(&id, &sei);
            }
            releaseSuite(inst.basic, kPrSDKColorManagementSuite, kPrSDKColorManagementSuiteVersion);
        }
        PluginLog::info("reframe/gpu/source: working colour space id err {} type {} (err {}); SEI primaries {} "
                        "transfer {} matrix {} bits {} full {} rgb {} scene {} (err {}); graphics white {} nits "
                        "(err {}), auto tone map {} (err {}), SDR gamma {} (err {})",
                        idErr, static_cast<int>(type), typeErr, sei.colorPrimariesCode,
                        sei.transferCharacteristicCode, sei.matrixEquationsCode, sei.bitDepth,
                        static_cast<int>(sei.isFullRange), static_cast<int>(sei.isRGB),
                        static_cast<int>(sei.isSceneReferred), seiErr, white, whiteErr, static_cast<int>(toneMap),
                        toneErr, gamma, gammaErr);
    } catch (...) {
        // Diagnostics must never take the effect down.
    }
}

void probeSourceGraph(const Instance& inst) noexcept {
    try {
        static std::atomic<bool> done{false};
        if (done.exchange(true)) {
            return;
        }
        const PrSDKVideoSegmentSuite* s = inst.segment;
        if (!s || inst.segmentVersion < kPrSDKVideoSegmentSuiteVersion6 || !s->AcquireOperatorOwnerNodeID ||
            !s->ReleaseVideoNodeID) {
            PluginLog::info("reframe/gpu/source: the Video Segment Suite (v{}) cannot walk to the owner node",
                            inst.segmentVersion);
            return;
        }
        logNode(*s, inst.nodeId, "effect");

        csSDK_int32 owner = 0;
        const prSuiteError ownerErr = s->AcquireOperatorOwnerNodeID(inst.nodeId, &owner);
        if (ownerErr != suiteError_NoError || owner == 0) {
            PluginLog::info("reframe/gpu/source: AcquireOperatorOwnerNodeID failed ({})", ownerErr);
            return;
        }
        logNode(*s, owner, "owner");

        // The owner's inputs: for a clip node, the media node.  Two levels
        // deep covers a clip whose input is itself wrapped (multicam, nest).
        csSDK_int32 inputs = 0;
        if (s->GetNodeInputCount && s->GetNodeInputCount(owner, &inputs) == suiteError_NoError &&
            s->AcquireInputNodeID) {
            for (csSDK_int32 i = 0; i < std::min<csSDK_int32>(inputs, 4); ++i) {
                PrTime offset = 0;
                csSDK_int32 input = 0;
                if (s->AcquireInputNodeID(owner, i, &offset, &input) != suiteError_NoError || input == 0) {
                    continue;
                }
                logNode(*s, input, "input");
                csSDK_int32 nested = 0;
                if (s->GetNodeInputCount && s->GetNodeInputCount(input, &nested) == suiteError_NoError) {
                    for (csSDK_int32 j = 0; j < std::min<csSDK_int32>(nested, 4); ++j) {
                        PrTime nestedOffset = 0;
                        csSDK_int32 grand = 0;
                        if (s->AcquireInputNodeID(input, j, &nestedOffset, &grand) == suiteError_NoError &&
                            grand != 0) {
                            logNode(*s, grand, "input-of-input");
                            s->ReleaseVideoNodeID(grand);
                        }
                    }
                }
                s->ReleaseVideoNodeID(input);
            }
        }
        // Clip time 0 through the owner's time transform: the media time the
        // first frame of the clip maps to (in point, speed, reverse applied).
        if (s->TransformNodeTime) {
            PrTime media = 0;
            const prSuiteError terr = s->TransformNodeTime(owner, 0, &media);
            PluginLog::info("reframe/gpu/source: TransformNodeTime(owner, 0) -> {} (err {})",
                            static_cast<long long>(media), terr);
        }
        s->ReleaseVideoNodeID(owner);

        probeWorkingColorSpace(inst);
    } catch (...) {
        // Diagnostics must never take the effect down.
    }
}

void probeParams(Instance& inst) noexcept {
    if (!inst.segment || !inst.segment->GetParamCount || !inst.segment->GetParam) {
        PluginLog::oncef("reframe/gpu/probe-nosuite", PluginLog::Level::Warn,
                         "reframe/gpu: the Video Segment Suite has no GetParamCount/GetParam; "
                         "using the static parameter mapping");
        return;
    }

    csSDK_int32 hostCount = 0;
    if (inst.segment->GetParamCount(inst.nodeId, &hostCount) != suiteError_NoError) {
        PluginLog::oncef("reframe/gpu/probe-count", PluginLog::Level::Warn,
                         "reframe/gpu: GetParamCount failed; using the static parameter mapping");
        return;
    }
    // Host-supplied, therefore validated: a negative count is garbage, and a
    // zero count is a node that exposes nothing to identify.
    if (hostCount <= 0) {
        PluginLog::oncef("reframe/gpu/probe-empty", PluginLog::Level::Warn,
                         "reframe/gpu: the host reports {} parameters; using the static parameter mapping",
                         hostCount);
        return;
    }

    // Read every entry the host admits to, but never more than our whole AE
    // list (group markers included) can account for: that is the longest
    // list either layout can be, so a longer one is not ours and there is no
    // reason to pay for the extra calls.  The array is sized by the same
    // constant, so the bound is structural.
    HostParamKind kinds[kParamCount] = {};
    const int probeCount = (hostCount > kParamCount) ? kParamCount : static_cast<int>(hostCount);
    std::string dump;
    dump.reserve(384);
    for (int i = 0; i < probeCount; ++i) {
        PrParam p{};
        // GetParam on a freshly created node fails INTERMITTENTLY: observed
        // on a live host (26.2.2) failing for a different subset of indices
        // on every CreateInstance, most often the angle controls, while the
        // same indices read fine moments later.  Treating one failure as a
        // type would poison the signature and send the whole effect back to
        // the static mapping - which is exactly what happened in the field:
        // playback (a lucky instance) animated while scrubbing (an unlucky
        // one) did not.  A few immediate retries cost nothing and turn an
        // intermittent read into a reliable one.
        constexpr int kReadAttempts = 8;
        prSuiteError readErr = suiteError_Fail;
        for (int attempt = 0; attempt < kReadAttempts; ++attempt) {
            std::memset(&p, 0, sizeof(p));
            readErr = inst.segment->GetParam(inst.nodeId, i, 0, &p);
            if (readErr == suiteError_NoError && kindOf(p) != HostParamKind::Unknown) {
                break;
            }
            // Yield rather than spin: whatever the host is still finishing
            // needs a moment, not CPU contention from this thread.
            std::this_thread::yield();
        }
        if (readErr != suiteError_NoError) {
            kinds[i] = HostParamKind::Unknown;
            dump += std::format("[{}]=<err> ", i);
            continue;
        }
        kinds[i] = kindOf(p);
        // The value is logged purely so a human reading the diagnostic can
        // sanity-check the identification; nothing here depends on it.
        switch (p.mType) {
            case kPrParamType_Float32: dump += std::format("[{}]f32:{:.3f} ", i, p.mFloat32); break;
            case kPrParamType_Float64: dump += std::format("[{}]f64:{:.3f} ", i, p.mFloat64); break;
            case kPrParamType_Int32:   dump += std::format("[{}]i32:{} ", i, p.mInt32); break;
            case kPrParamType_Bool:    dump += std::format("[{}]bool:{} ", i, p.mBool ? 1 : 0); break;
            default:                   dump += std::format("[{}]type{} ", i, static_cast<int>(p.mType)); break;
        }
    }

    // The one-time dump: the ground truth this whole mechanism was built
    // from.  Logged whatever the outcome, because it is just as useful when
    // the probe SUCCEEDS (it shows which controls the host hid) as when it
    // fails (it shows what to teach the matcher next).
    PluginLog::oncef("reframe/gpu/paramdump", PluginLog::Level::Info,
                     "reframe/gpu: host parameter dump at t=0 ({} of {} entries, we added {}): {}", probeCount,
                     hostCount, OSV_REFRAME_PARAM_COUNT, dump);

    // ---- identify the layout ---------------------------------------------------
    // The two layouts cannot be confused: the verbatim one is exactly
    // kParamCount entries long, the compact one at most kValueParamCount.
    // Anything else is a list nobody has seen yet, and guessing at it would
    // mean reading someone else's controls.
    HostParamMap probed{};
    const char* layout = nullptr;
    if (matchVerbatimLayout(kinds, probeCount, static_cast<int>(hostCount), &probed)) {
        layout = "verbatim (host index = AE index - 1, group markers included)";
    } else if (hostCount <= kValueParamCount && matchHostParams(kinds, probeCount, &probed)) {
        layout = "compact (group markers dropped)";
    }
    if (!layout) {
        PluginLog::oncef("reframe/gpu/probe-nomatch", PluginLog::Level::Error,
                         "reframe/gpu: the host reports {} parameters and their types do not match this effect's "
                         "signature ({} entries including group markers, {} without); falling back to the static "
                         "mapping (AE index - 1), which may read the wrong control",
                         hostCount, kParamCount, kValueParamCount);
        return;
    }

    inst.paramMap = probed;
    inst.paramMapProbed = true;

    // Which AE index reads which host entry, straight from the tables, so a
    // control added to ReframeParams.h shows up here without an edit.
    std::string pairs;
    pairs.reserve(8 * kValueParamCount);
    for (int i = 0; i < kValueParamCount; ++i) {
        const int aeIndex = kValueParamAeIndex[i];
        pairs += std::format("{}->{} ", aeIndex, probed[aeIndex]);
    }
    PluginLog::oncef("reframe/gpu/probe-ok", PluginLog::Level::Info,
                     "reframe/gpu: probed the host parameter mapping from {} entries, {} layout - AE index -> host "
                     "index: {}(-1 = not exposed by the host)",
                     hostCount, layout, pairs);
}

/// An angle control: PF_ADD_ANGLE arrives as mFloat32 degrees.  Other types
/// are accepted defensively (a host that changed its mind about the union
/// member must not silently give us zero).
double readAngle(const Instance& inst, int aeIndex, PrTime time, double fallback) noexcept {
    PrParam p{};
    if (!readParam(inst, aeIndex, time, &p)) {
        return fallback;
    }
    switch (p.mType) {
        case kPrParamType_Float32:
            return static_cast<double>(p.mFloat32);
        case kPrParamType_Float64:
            return p.mFloat64;
        case kPrParamType_Int32:
            return static_cast<double>(p.mInt32);
        default:
            return fallback;
    }
}

/// A float slider: PF_ADD_FLOAT_SLIDERX arrives as mFloat64.
double readFloat(const Instance& inst, int aeIndex, PrTime time, double fallback) noexcept {
    PrParam p{};
    if (!readParam(inst, aeIndex, time, &p)) {
        return fallback;
    }
    switch (p.mType) {
        case kPrParamType_Float64:
            return p.mFloat64;
        case kPrParamType_Float32:
            return static_cast<double>(p.mFloat32);
        default:
            return fallback;
    }
}

/// A popup: mInt32, as the host numbers it - which on the GPU side need not
/// be 1-based; readSettings() decodes it with decodeHostPopup().  Returns
/// false (and leaves `out` alone) when the host did not answer with an
/// integer, so a caller can tell a real reading from its own fallback: only
/// a real reading may be decoded or teach the instance anything.
bool readPopupRaw(const Instance& inst, int aeIndex, PrTime time, int* out) noexcept {
    if (!out) {
        return false;
    }
    PrParam p{};
    if (!readParam(inst, aeIndex, time, &p)) {
        return false;
    }
    switch (p.mType) {
        case kPrParamType_Int32:
            *out = p.mInt32;
            return true;
        case kPrParamType_Int16:
            *out = static_cast<int>(p.mInt16);
            return true;
        case kPrParamType_Int8:
            *out = static_cast<int>(p.mInt8);
            return true;
        default:
            return false;
    }
}

/// A checkbox: mBool.
bool readBool(const Instance& inst, int aeIndex, PrTime time, bool fallback) noexcept {
    PrParam p{};
    if (!readParam(inst, aeIndex, time, &p)) {
        return fallback;
    }
    switch (p.mType) {
        case kPrParamType_Bool:
            return p.mBool != 0;
        case kPrParamType_Int32:
            return p.mInt32 != 0;
        default:
            return fallback;
    }
}

/// Read every control at `time`, applying the "Smooth Keyframes" average
/// over t-1, t and t+1 frames to the six angle dials when it is on.
///
/// Averaging the ANGLES (not the frames) is what makes the smoothing cheap:
/// it needs no extra input frames, so GetFrameDependencies can keep saying
/// "only the current frame", and it produces the same numbers as the CPU
/// path, which does the same three-sample average through PF_CHECKOUT_PARAM.
Settings readSettings(const Instance& inst, PrTime clipTime, PrTime ticksPerFrame) noexcept {
    Settings s;

    // ---- the popups, in the host's own numbering -------------------------------
    // [WP-CAMERA] Premiere hands GPU filters popups numbered from 0 where the
    // CPU path (and the mock host) number them from 1 (PopupBase in
    // ReframeParams.h).  Both raw values are read FIRST and both are allowed
    // to settle the base before either is decoded, so a Preset reading 0 on
    // this very frame already corrects an ambiguous Output Resolution.  A
    // control the host did not answer takes its documented (1-based) default
    // directly: it was never in the host's numbering, so it is neither
    // decoded nor allowed to teach the instance anything.
    int rawResolution = 0;
    int rawPreset = 0;
    const bool haveResolution = readPopupRaw(inst, kIndexOutputResolution, clipTime, &rawResolution);
    const bool havePreset = readPopupRaw(inst, kIndexPreset, clipTime, &rawPreset);
    PopupBase base = static_cast<PopupBase>(inst.popupBase.load(std::memory_order_relaxed));
    if (haveResolution) {
        (void)decodeHostPopup(rawResolution, OSV_REFRAME_RESOLUTION_COUNT, &base);
    }
    if (havePreset) {
        (void)decodeHostPopup(rawPreset, OSV_REFRAME_PRESET_COUNT, &base);
    }
    const PopupBase learned = base;
    s.resolution = sanitiseResolution(haveResolution
                                          ? decodeHostPopup(rawResolution, OSV_REFRAME_RESOLUTION_COUNT, &base)
                                          : OSV_REFRAME_RESOLUTION_DEFAULT);
    s.preset = sanitisePreset(havePreset ? decodeHostPopup(rawPreset, OSV_REFRAME_PRESET_COUNT, &base)
                                         : OSV_REFRAME_PRESET_DEFAULT);
    if (learned != PopupBase::Unknown) {
        const int previous = inst.popupBase.exchange(static_cast<int>(learned), std::memory_order_relaxed);
        if (previous != static_cast<int>(learned)) {
            PluginLog::info("reframe/gpu: this host numbers popups from {} (Output Resolution read {}, Preset {})",
                            learned == PopupBase::Zero ? 0 : 1, rawResolution, rawPreset);
        }
    }

    s.fovDeg = readFloat(inst, kIndexFov, clipTime, OSV_REFRAME_FOV_DEFAULT);
    s.distortion = readFloat(inst, kIndexDistortion, clipTime, OSV_REFRAME_DISTORTION_DEFAULT);
    s.smoothKeyframes = readBool(inst, kIndexSmooth, clipTime, false);

    // ---- [WP-CAMERA] DJI's camera ----------------------------------------------
    // Camera Model is a checkbox, so it reads the same on every host; a host
    // that does not expose it (or a probe that mapped it to nothing) yields
    // Classic, the lens every project had before the control existed.  Zoom
    // and Drag Sensitivity are never rendered from but are read so the
    // Settings block is complete for the log line on a rejected setup.
    s.cameraModel = cameraModelFromCheckbox(
        readBool(inst, kIndexCameraModel, clipTime, OSV_REFRAME_CAMERA_MODEL_DEFAULT != 0) ? 1 : 0);
    s.zoomDeg = readFloat(inst, kIndexZoom, clipTime, OSV_REFRAME_ZOOM_DEFAULT);
    s.djiFovDeg = readFloat(inst, kIndexDjiFov, clipTime, OSV_REFRAME_DJI_FOV_DEFAULT);
    s.correction = readFloat(inst, kIndexCorrection, clipTime, OSV_REFRAME_CORRECTION_DEFAULT);
    s.dragSensitivity = readFloat(inst, kIndexDragSensitivity, clipTime, OSV_REFRAME_DRAG_SENSITIVITY_DEFAULT);

    // The six angles, either sampled once or averaged over three frames.
    const int angleIndices[6] = {kIndexPan,       kIndexTilt,       kIndexRoll,
                                 kIndexSourcePan, kIndexSourceTilt, kIndexSourceRoll};
    double angles[6] = {0, 0, 0, 0, 0, 0};

    // Smoothing needs a frame duration; without one (a host that could not
    // tell us) it degrades to no smoothing rather than to a wrong average.
    const bool smooth = s.smoothKeyframes && ticksPerFrame > 0;
    for (int i = 0; i < 6; ++i) {
        const double centre = readAngle(inst, angleIndices[i], clipTime, 0.0);
        if (!smooth) {
            angles[i] = centre;
            continue;
        }
        // Clamp the neighbours to non-negative clip time: asking before the
        // clip start returns the first keyframe on a real host, but a
        // negative PrTime is not something every host is happy with.
        const PrTime before = (clipTime > ticksPerFrame) ? (clipTime - ticksPerFrame) : 0;
        const PrTime after = clipTime + ticksPerFrame;
        const double prev = readAngle(inst, angleIndices[i], before, centre);
        const double next = readAngle(inst, angleIndices[i], after, centre);
        angles[i] = (prev + centre + next) / 3.0;
    }

    s.panDeg = angles[0];
    s.tiltDeg = angles[1];
    s.rollDeg = angles[2];
    s.sourcePanDeg = angles[3];
    s.sourceTiltDeg = angles[4];
    s.sourceRollDeg = angles[5];
    return s;
}

/// Pixel size of the sequence, or an invalid size when the suite cannot tell
/// us (the caller then falls back to the output frame's own size).
///
/// The GPU instance already holds the timeline id and the suite, so unlike
/// the CPU path this needs no acquire / release dance.
SizePx sequenceSize(const Instance& inst) noexcept {
    if (!inst.sequence || !inst.sequence->GetFrameRect) {
        return SizePx{};
    }
    prRect rect{};
    if (inst.sequence->GetFrameRect(inst.timelineId, &rect) != suiteError_NoError) {
        return SizePx{};
    }
    // Host-supplied, therefore validated: an inverted or absurd rectangle is
    // reported as "unknown" rather than carried into the camera.
    const long long w = static_cast<long long>(rect.right) - static_cast<long long>(rect.left);
    const long long h = static_cast<long long>(rect.bottom) - static_cast<long long>(rect.top);
    if (w <= 0 || h <= 0 || w > kMaxSequenceEdge || h > kMaxSequenceEdge) {
        return SizePx{};
    }
    return SizePx{static_cast<int>(w), static_cast<int>(h)};
}

