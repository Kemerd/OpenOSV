// GpuFilter.cpp - the xGPUFilterEntry side of Open 360 Reframe.
//
// Premiere binds a GPU renderer to a software effect BY MATCH NAME: the
// module exports xGPUFilterEntry, reports PrGPUFilterInfo with the same
// string EffectMain's PiPL carries, and from then on every frame the host
// can accelerate is routed here instead of to PF_Cmd_RENDER.
//
// Deliberate design choices, each with its reason:
//
//   * The module glue is written here rather than taken from the SDK's
//     GPUVideoFilter/Utils/PrGPUFilterModule.h.  That header pulls in
//     Boost.Preprocessor (through PrGPU/KernelSupport) and unconditionally
//     acquires PF_TransitionSuite, neither of which an effect needs; it is
//     also a C++ class hierarchy that would force our state into its shape.
//     The five function pointers of PrGPUFilter are trivial to fill by hand.
//
//   * CUDA is used STRICTLY through the driver API (cuda.h, nvcuda.dll).
//     The SDK guide ranks that first for compatibility (12.1.2) and it means
//     the .aex never loads a cudart DLL, so it cannot collide with the copy
//     Premiere itself ships.  The kernel comes from an embedded fatbin, not
//     from a linked device object, for the same reason.
//
//   * The host's CUcontext is pushed around every driver call.  The GPU
//     Device Suite says exclusive access is always held for a "full GPU
//     plug-in" and that the context is current on the render thread, but
//     CreateInstance is NOT documented to run on a render thread, and
//     pushing an already-current context is cheap and always correct.
//
//   * Modules are cached per device in a mutex-guarded static table, because
//     CreateInstance is called again on EVERY parameter change and loading a
//     fatbin per keyframe would dominate the render.
//
// Every extern "C" boundary catches (...): an exception unwinding into
// Premiere's C call stack is undefined behaviour and would take the host
// down with it.

