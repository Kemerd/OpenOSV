prSuiteError render(PrGPUFilterInstance* instanceData, const PrGPUFilterRenderParams* renderParams,
                    const PPixHand* inFrames, csSDK_size_t inFrameCount, PPixHand* outFrame) noexcept {
    try {
        // ---- argument checks --------------------------------------------
        if (!instanceData || !renderParams || !inFrames || !outFrame || inFrameCount < 1) {
            return suiteError_InvalidParms;
        }
        Instance* inst = static_cast<Instance*>(instanceData->ioPrivatePluginData);
        if (!inst || !inst->alive() || !inst->kernel || !inst->context) {
            return suiteError_InvalidParms;
        }

        const GpuFrame src = inspectFrame(*inst, inFrames[0]);
        const GpuFrame dst = inspectFrame(*inst, *outFrame);
        if (!src.valid || !dst.valid) {
            PluginLog::oncef("reframe/gpu/frame", PluginLog::Level::Error,
                             "reframe/gpu: unusable frame (src {}x{} valid={}, dst {}x{} valid={})", src.width,
                             src.height, src.valid, dst.width, dst.height, dst.valid);
            return suiteError_Fail;
        }
        // Once per process: what the GPU path is actually handed, and the two
        // clocks, so the clip-time -> media-frame mapping the direct renderer
        // needs can be checked against a real host.
        PluginLog::oncef("reframe/gpu/first-frame", PluginLog::Level::Info,
                         "reframe/gpu: first GPU frame - src {}x{} {}, dst {}x{} {}, clip time {}, sequence time {}, "
                         "quality {}, downsample {:.3f}x{:.3f}, ticks/frame {}, host stream {}",
                         src.width, src.height, src.isHalf ? "16f" : "32f", dst.width, dst.height,
                         dst.isHalf ? "16f" : "32f", static_cast<long long>(renderParams->inClipTime),
                         static_cast<long long>(renderParams->inSequenceTime),
                         static_cast<int>(renderParams->inQuality), renderParams->inDownsampleFactorX,
                         renderParams->inDownsampleFactorY, static_cast<long long>(renderParams->inRenderTicksPerFrame),
                         static_cast<const void*>(inst->stream));

        // The host hands us an output in the same format as the input; if it
        // ever did not, writing half into a float buffer would corrupt it.
        if (src.isHalf != dst.isHalf) {
            PluginLog::error("reframe/gpu: input and output pixel formats differ");
            return suiteError_Fail;
        }

        // ---- parameters --------------------------------------------------
        // Retry the probe if CreateInstance could not identify the host's
        // index space.  GetParam fails intermittently on a node the host has
        // only just built, and an instance that gave up at creation would
        // read the wrong controls for as long as it lived - the field
        // symptom being that playback animated (an instance whose probe had
        // got lucky) while scrubbing did not.  Reaching Render proves the
        // node is ready, so this is the moment a retry succeeds.
        if (!inst->paramMapProbed) {
            probeParams(*inst);
        }
        const Settings settings = readSettings(*inst, renderParams->inClipTime, renderParams->inRenderTicksPerFrame);

        // The frame we render into is the one the host allocated; its size
        // is the render size, which may differ from the input's.
        ConstFrameView srcView;
        srcView.base = src.data;
        srcView.rowBytes = src.rowBytes;
        srcView.width = src.width;
        srcView.height = src.height;
        srcView.layout = src.isHalf ? PixelLayout::Bgra16f : PixelLayout::Bgra32f;
        srcView.topDown = true;  // "GPU Frames always have origin top left"

        const KernelSetup setup = buildParams(settings, srcView, dst.width, dst.height, sequenceSize(*inst));
        if (!setup.valid) {
            PluginLog::oncef("reframe/gpu/setup", PluginLog::Level::Error,
                             "reframe/gpu: could not build the kernel parameters ({}x{} -> {}x{}): {}", src.width,
                             src.height, dst.width, dst.height, setupRejectName(setup.reject));
            return suiteError_Fail;
        }

        // ---- launch -------------------------------------------------------
        ContextScope scope(inst->context);
        if (!scope.ok()) {
            PluginLog::error("reframe/gpu: cuCtxPushCurrent failed at render time");
            return suiteError_Fail;
        }

        // ---- the direct path: straight from the fisheyes ----------------------
        // Sharper than sampling the equirect (one resampling instead of two,
        // at the fisheyes' own resolution) and independent of the equirect
        // size the importer was asked for.  Any failure falls through to the
        // equirect kernel below, which overwrites the whole output.
        if (!inst->directDisabled && inst->source.ok && inst->directTransfer >= 0 &&
            osv::reframe::direct::engine().ok()) {
            osv::reframe::direct::DirectRequest request;
            request.source = &inst->source;
            request.segment = inst->segment;
            request.clipTime = renderParams->inClipTime;
            request.transfer = inst->directTransfer;
            request.context = inst->context;
            request.kernel = directKernelFor(inst->deviceIndex, inst->context);
            request.settings = settings;
            request.output.data = dst.data;
            request.output.rowBytes = dst.rowBytes;
            request.output.width = dst.width;
            request.output.height = dst.height;
            request.output.isHalf = dst.isHalf;
            request.sequenceSize = sequenceSize(*inst);
            std::string reason;
            if (request.kernel && osv::reframe::direct::renderDirect(request, reason)) {
                PluginLog::oncef("reframe/direct/first", PluginLog::Level::Info,
                                 "reframe/direct: rendering straight from the fisheyes ({}x{} {})", dst.width,
                                 dst.height, dst.isHalf ? "16f" : "32f");
                instanceData->outIsRealtime = kPrTrue;
                return suiteError_NoError;
            }
            if (!request.kernel) {
                reason = "the fused kernel is not loaded";
            }
            // [WP-SETTINGS] A deliberate hand-over by the Source Settings rule
            // is not a failure: DirectPath logged it once for the change that
            // caused it, and a later change can make the clip eligible, so
            // the instance neither warns nor stops asking.
            if (!osv::reframe::direct::isPolicyFallback(reason)) {
                // Structural failures (the setup cannot express the view, the
                // engine cannot open the file, the ABI changed) will fail again
                // on every frame; stop trying for this instance.  Everything
                // else - a decode hiccup - may pass, so the next frame retries.
                const bool structural = reason.rfind("setup:", 0) == 0 ||
                                        reason.find("cannot open") != std::string::npos ||
                                        reason.find("layout") != std::string::npos ||
                                        reason.find("not loaded") != std::string::npos;
                if (structural) {
                    inst->directDisabled = true;
                }
                if (inst->directFailures < 5) {
                    ++inst->directFailures;
                    PluginLog::warn("reframe/direct: falling back to the equirect path for this frame{} - {}",
                                    structural ? " and this instance" : "", reason);
                }
            }
        }

        // buildParams() computed sourceRow0 as a HOST pointer arithmetic on
        // the device address; for a top-down frame that is the base itself,
        // which is what we pass. The kernel adds y * pitchBytes.
        const void* srcDevice = setup.sourceRow0;
        OsvReframeParams params = setup.params;
        OsvRgbaSource source = setup.source;
        void* dstDevice = dst.data;
        int dstRowBytes = dst.rowBytes;
        int dstIsHalf = dst.isHalf ? 1 : 0;

        void* args[] = {&params, &source, &srcDevice, &dstDevice, &dstRowBytes, &dstIsHalf};

        const unsigned gridX = (static_cast<unsigned>(dst.width) + kBlockDimX - 1u) / kBlockDimX;
        const unsigned gridY = (static_cast<unsigned>(dst.height) + kBlockDimY - 1u) / kBlockDimY;

        // ORDERING, on both sides of the kernel - the way Adobe's own CUDA
        // sample (GPUVideoFilter/Vignette/Vignette.cu) does it: launch on the
        // context's LEGACY default stream, then wait for it before handing
        // the frame back.
        //
        //  * Before: the legacy stream implicitly waits for all work already
        //    queued on the context's blocking streams, which is where the
        //    host uploads and converts our INPUT frame.  A launch on some
        //    other stream could start sampling an input that was still being
        //    written.
        //  * After: Render returning is the host's signal that the OUTPUT is
        //    ready.  The first real GPU session (the first ever, once the
        //    match-name binding was fixed) launched on the device's command
        //    queue and returned at once: the host consumed frames the kernel
        //    had not finished, and every row the kernel had not reached yet
        //    showed whatever stale VRAM the recycled buffer held - blocky
        //    garbage in the lower part of the view while panning.
        //
        // The wait costs the kernel's own run time (~0.3 ms for a 2560x1440
        // view, a few ms for a 6000x3000 frame) and nothing else: only this
        // stream is synchronised, not the whole context.
        const CUstream launchStream = CU_STREAM_LEGACY;
        CUresult r = cuLaunchKernel(inst->kernel, gridX, gridY, 1u, kBlockDimX, kBlockDimY, 1u, 0u, launchStream, args,
                                    nullptr);
        if (r != CUDA_SUCCESS) {
            PluginLog::error("reframe/gpu: {}", cudaMessage("cuLaunchKernel", r));
            return suiteError_Fail;
        }
        r = cuStreamSynchronize(launchStream);
        if (r != CUDA_SUCCESS) {
            // The kernel itself failed (a fault) or the context is broken; the
            // output cannot be trusted either way.
            PluginLog::error("reframe/gpu: {}", cudaMessage("cuStreamSynchronize", r));
            return suiteError_Fail;
        }

        instanceData->outIsRealtime = kPrTrue;
        return suiteError_NoError;
    } catch (...) {
        return suiteError_Fail;
    }
}

