/// Everything we need to know about one GPU frame.
struct GpuFrame {
    void* data = nullptr;
    std::int32_t rowBytes = 0;
    int width = 0;
    int height = 0;
    bool isHalf = false;
    bool valid = false;
};

/// Query a GPU PPix through the PPix and GPU Device suites.
GpuFrame inspectFrame(const Instance& inst, PPixHand hand) noexcept {
    GpuFrame f;
    if (!hand || !inst.ppix || !inst.gpu) {
        return f;
    }
    if (!inst.ppix->GetBounds || !inst.ppix->GetRowBytes || !inst.ppix->GetPixelFormat || !inst.gpu->GetGPUPPixData) {
        return f;
    }

    void* data = nullptr;
    if (inst.gpu->GetGPUPPixData(hand, &data) != suiteError_NoError || !data) {
        return f;
    }
    csSDK_int32 rowBytes = 0;
    if (inst.ppix->GetRowBytes(hand, &rowBytes) != suiteError_NoError || rowBytes <= 0) {
        return f;
    }
    prRect bounds{};
    if (inst.ppix->GetBounds(hand, &bounds) != suiteError_NoError) {
        return f;
    }
    PrPixelFormat format = PrPixelFormat_Invalid;
    if (inst.ppix->GetPixelFormat(hand, &format) != suiteError_NoError) {
        return f;
    }
    if (format != PrPixelFormat_GPU_BGRA_4444_32f && format != PrPixelFormat_GPU_BGRA_4444_16f) {
        // "Result must be in the same pixel format as the input"
        // (PrSDKGPUFilter.h) and only these two GPU formats exist.
        return f;
    }

    f.data = data;
    f.rowBytes = static_cast<std::int32_t>(rowBytes);
    f.width = static_cast<int>(bounds.right - bounds.left);
    f.height = static_cast<int>(bounds.bottom - bounds.top);
    f.isHalf = (format == PrPixelFormat_GPU_BGRA_4444_16f);
    // A pitch that cannot hold one row means the header is wrong; refuse it
    // rather than walk off the allocation.
    const std::size_t bpp = f.isHalf ? 8u : 16u;
    f.valid = f.width > 0 && f.height > 0 &&
              static_cast<std::size_t>(f.rowBytes) >= static_cast<std::size_t>(f.width) * bpp;
    return f;
}

