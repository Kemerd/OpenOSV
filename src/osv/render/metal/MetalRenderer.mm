// ---------------------------------------------------------------------------
//  Buffer indices of kernel.metal (keep in step with its header comment).
// ---------------------------------------------------------------------------
constexpr NSUInteger kBufParams = 0;
constexpr NSUInteger kBufPlane[2][4] = {{1, 2, 3, 4}, {5, 6, 7, 8}};  // y, u, v, descriptor
constexpr NSUInteger kBufSeam = 9;
constexpr NSUInteger kBufWarp = 10;
constexpr NSUInteger kBufBlendSeam = 11;
constexpr NSUInteger kBufPhoto = 12;
constexpr NSUInteger kBufSeamLow = 13;
constexpr NSUInteger kBufOut = 14;
constexpr NSUInteger kBufOutPitch = 15;
// osvSeamLowDecimate writes its output to buffer 9; osvSeamLowBlur takes
// params, src, dst, horizontal at 0..3.
constexpr NSUInteger kBufDecimateOut = 9;

/// UTF-8 copy of an NSString (empty for nil).
std::string utf8(NSString* s) {
    if (s == nil) {
        return {};
    }
    const char* c = [s UTF8String];
    return c ? std::string(c) : std::string();
}

/// Every Metal device: the system default first (the GPU a Mac drives its
/// displays with, and the one Premiere renders on by default), then the rest
/// in the order Metal lists them.
NSArray<id<MTLDevice>>* enumerateDevices() {
    NSMutableArray<id<MTLDevice>>* list = [NSMutableArray array];
    id<MTLDevice> preferred = MTLCreateSystemDefaultDevice();
    if (preferred != nil) {
        [list addObject:preferred];
    }
    NSArray<id<MTLDevice>>* all = MTLCopyAllDevices();
    for (id<MTLDevice> d in all) {
        if (d != nil && ![list containsObject:d]) {
            [list addObject:d];
        }
    }
    return list;
}

/// A shared-storage buffer that only grows (the CPU writes, the GPU reads,
/// or the other way round, through the same memory on Apple Silicon).
struct MtlBuffer {
    id<MTLBuffer> buffer = nil;
    std::size_t bytes = 0;

    Status ensure(id<MTLDevice> device, std::size_t needed) {
        if (needed == 0) {
            needed = sizeof(float);  // Metal refuses a zero-length buffer
        }
        if (buffer != nil && needed <= bytes) {
            return okStatus();
        }
        buffer = nil;
        bytes = 0;
        if (device == nil) {
            return failStatus(ErrorCode::Gpu, "Metal: no device");
        }
        if (needed > static_cast<std::size_t>([device maxBufferLength])) {
            return failStatus(ErrorCode::Gpu, "Metal: buffer of " + std::to_string(needed) +
                                                  " bytes exceeds the device's maximum");
        }
        buffer = [device newBufferWithLength:needed options:MTLResourceStorageModeShared];
        if (buffer == nil) {
            return failStatus(ErrorCode::Gpu, "Metal: cannot allocate " + std::to_string(needed) + " bytes");
        }
        bytes = needed;
        return okStatus();
    }

    /// Host pointer to the contents (shared storage), or nullptr.
    [[nodiscard]] void* contents() const noexcept { return buffer != nil ? [buffer contents] : nullptr; }
};

/// Copy `rows` rows of `rowBytes` each from a strided host plane into a
/// tightly packed buffer.
Status copyRows(MtlBuffer& dst, const void* src, std::size_t rowBytes, std::size_t srcPitchBytes, std::size_t rows) {
    if (!src || rowBytes == 0 || rows == 0 || srcPitchBytes < rowBytes) {
        return failStatus(ErrorCode::InvalidArgument, "Metal: bad plane geometry");
    }
    auto* out = static_cast<unsigned char*>(dst.contents());
    if (!out || dst.bytes < rowBytes * rows) {
        return failStatus(ErrorCode::Internal, "Metal: plane buffer too small");
    }
    const auto* in = static_cast<const unsigned char*>(src);
    if (srcPitchBytes == rowBytes) {
        std::memcpy(out, in, rowBytes * rows);
        return okStatus();
    }
    for (std::size_t r = 0; r < rows; ++r) {
        std::memcpy(out + r * rowBytes, in + r * srcPitchBytes, rowBytes);
    }
    return okStatus();
}

/// Threads per threadgroup for a 2-D (or 2-D x lens) dispatch of `pipeline`:
/// one SIMD group wide, as many rows as the pipeline allows up to 8.
MTLSize threadgroupFor(id<MTLComputePipelineState> pipeline) {
    const NSUInteger width = std::max<NSUInteger>(1, [pipeline threadExecutionWidth]);
    const NSUInteger maxThreads = std::max<NSUInteger>(width, [pipeline maxTotalThreadsPerThreadgroup]);
    const NSUInteger height = std::clamp<NSUInteger>(maxThreads / width, 1, 8);
    return MTLSizeMake(width, height, 1);
}

/// Threadgroups covering a w x h (x depth) grid; the kernels guard the edges,
/// so no non-uniform threadgroup support is needed.
MTLSize groupsFor(MTLSize group, NSUInteger w, NSUInteger h, NSUInteger depth) {
    return MTLSizeMake((w + group.width - 1) / group.width, (h + group.height - 1) / group.height, depth);
}

