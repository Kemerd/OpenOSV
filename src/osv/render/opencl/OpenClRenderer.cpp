/**
 * @brief Format an OpenCL status code into a human-readable diagnostic string.
 *
 * @param what  Operation name that produced the error.
 * @param err   OpenCL status code.
 * @return      Formatted diagnostic message.
 */
std::string clMessage(const char* what, cl_int err) {
    return std::format("{}: OpenCL error {}", what ? what : "OpenCL", static_cast<int>(err));
}

/**
 * @brief Convert a string to ASCII lower-case for case-insensitive matching.
 *
 * @param s  Input string view.
 * @return   Lower-cased copy of `s`.
 */
std::string lowerAscii(std::string_view s) {
    std::string out(s);
    std::transform(out.begin(), out.end(), out.begin(),
                   [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
    return out;
}

/**
 * @brief Trim leading and trailing ASCII whitespace from a string view.
 *
 * @param s  Input string view.
 * @return   Trimmed sub-view.
 */
std::string_view trimAscii(std::string_view s) noexcept {
    while (!s.empty() && std::isspace(static_cast<unsigned char>(s.front()))) {
        s.remove_prefix(1);
    }
    while (!s.empty() && std::isspace(static_cast<unsigned char>(s.back()))) {
        s.remove_suffix(1);
    }
    return s;
}

/**
 * @brief Case-insensitive substring search in ASCII strings.
 *
 * @param haystack  Text to search within.
 * @param needle    Substring to search for.
 * @return          True when `needle` occurs inside `haystack`.
 */
bool containsIgnoreCase(std::string_view haystack, std::string_view needle) {
    if (needle.empty()) {
        return true;
    }
    const std::string h = lowerAscii(haystack);
    const std::string n = lowerAscii(needle);
    return h.find(n) != std::string::npos;
}

/// Process-wide mutex protecting `g_preferredDevice`.
std::mutex g_preferredDeviceMutex;

/// Optional preferred OpenCL device selector set via `OpenClRenderer::setPreferredDevice`.
std::string g_preferredDevice;

/**
 * @brief Return the active OpenCL device selector from `--cl-device` or the environment.
 *
 * Checks the explicit process-wide override first, then falls back to the
 * `OSV_CL_DEVICE` and `OSV_OPENCL_DEVICE` environment variables.
 *
 * @return  Trimmed selector string, or empty when automatic selection is active.
 */
std::string effectiveDeviceSelector() {
    {
        std::lock_guard<std::mutex> lock(g_preferredDeviceMutex);
        const std::string_view trimmed = trimAscii(g_preferredDevice);
        if (!trimmed.empty()) {
            return std::string(trimmed);
        }
    }
    // Check environment variables when no CLI flag override was set.
    for (const char* envName : {"OSV_CL_DEVICE", "OSV_OPENCL_DEVICE"}) {
        if (const char* val = std::getenv(envName)) {
            const std::string_view trimmed = trimAscii(val);
            if (!trimmed.empty()) {
                return std::string(trimmed);
            }
        }
    }
    return {};
}

/**
 * @brief One enumerated OpenCL device and its hardware capabilities for ranking.
 */
struct DeviceEntry {
    cl_platform_id platform = nullptr;
    cl_device_id device = nullptr;
    bool isGpu = false;
    bool isDiscreteGpu = false;
    bool isTranslationLayer = false;
    std::uint64_t globalMemBytes = 0;
    std::uint32_t computeUnits = 0;
    std::string name;
    std::string vendor;
    std::string platformName;
};

/**
 * @brief Enumerate every OpenCL device across all platforms, ranked best-first.
 *
 * Ranking order:
 *   1. Real GPU devices (`CL_DEVICE_TYPE_GPU`) before CPU / accelerator devices;
 *   2. Native vendor ICDs before translation layers (`OpenCLOn12`, Basic Render);
 *   3. Discrete GPUs (`CL_DEVICE_HOST_UNIFIED_MEMORY == CL_FALSE`) before iGPUs;
 *   4. Larger global memory (`CL_DEVICE_GLOBAL_MEM_SIZE`) and compute unit count.
 *
 * @return  Sorted list of available OpenCL devices.
 */
std::vector<DeviceEntry> enumerateDevices() {
    std::vector<DeviceEntry> result;
    cl_uint platformCount = 0;
    if (clGetPlatformIDs(0, nullptr, &platformCount) != CL_SUCCESS || platformCount == 0) {
        return result;
    }
    std::vector<cl_platform_id> platforms(platformCount);
    if (clGetPlatformIDs(platformCount, platforms.data(), nullptr) != CL_SUCCESS) {
        return result;
    }
    // Walk each OpenCL platform and query its devices.
    for (cl_platform_id platform : platforms) {
        if (!platform) {
            continue;
        }
        char platBuf[256] = {};
        clGetPlatformInfo(platform, CL_PLATFORM_NAME, sizeof(platBuf) - 1, platBuf, nullptr);
        const std::string platName = platBuf;

        cl_uint deviceCount = 0;
        if (clGetDeviceIDs(platform, CL_DEVICE_TYPE_ALL, 0, nullptr, &deviceCount) != CL_SUCCESS || deviceCount == 0) {
            continue;
        }
        std::vector<cl_device_id> devices(deviceCount);
        if (clGetDeviceIDs(platform, CL_DEVICE_TYPE_ALL, deviceCount, devices.data(), nullptr) != CL_SUCCESS) {
            continue;
        }
        // Populate hardware capabilities for each device on this platform.
        for (cl_device_id dev : devices) {
            if (!dev) {
                continue;
            }
            DeviceEntry e;
            e.platform = platform;
            e.device = dev;
            e.platformName = platName;

            cl_device_type type = 0;
            clGetDeviceInfo(dev, CL_DEVICE_TYPE, sizeof(type), &type, nullptr);
            e.isGpu = (type & CL_DEVICE_TYPE_GPU) != 0;

            cl_bool unified = CL_FALSE;
            clGetDeviceInfo(dev, CL_DEVICE_HOST_UNIFIED_MEMORY, sizeof(unified), &unified, nullptr);
            e.isDiscreteGpu = e.isGpu && (unified == CL_FALSE);

            cl_ulong globalMem = 0;
            clGetDeviceInfo(dev, CL_DEVICE_GLOBAL_MEM_SIZE, sizeof(globalMem), &globalMem, nullptr);
            e.globalMemBytes = static_cast<std::uint64_t>(globalMem);

            cl_uint units = 0;
            clGetDeviceInfo(dev, CL_DEVICE_MAX_COMPUTE_UNITS, sizeof(units), &units, nullptr);
            e.computeUnits = static_cast<std::uint32_t>(units);

            char buffer[256] = {};
            clGetDeviceInfo(dev, CL_DEVICE_NAME, sizeof(buffer) - 1, buffer, nullptr);
            const std::string devName( trimAscii(buffer) );

            char vendorBuf[256] = {};
            clGetDeviceInfo(dev, CL_DEVICE_VENDOR, sizeof(vendorBuf) - 1, vendorBuf, nullptr);
            e.vendor = std::string(trimAscii(vendorBuf));

            char version[128] = {};
            clGetDeviceInfo(dev, CL_DEVICE_VERSION, sizeof(version) - 1, version, nullptr);
            e.name = devName + " (" + std::string(trimAscii(version)) + ")";

            // Deprioritize D3D12 translation layers and software fallback adapters.
            e.isTranslationLayer = containsIgnoreCase(platName, "OpenCLOn12") ||
                                   containsIgnoreCase(devName, "OpenCLOn12") ||
                                   containsIgnoreCase(devName, "Basic Render Driver");
            result.push_back(std::move(e));
        }
    }
    // Sort devices so the strongest discrete GPU is index 0 by default.
    std::stable_sort(result.begin(), result.end(), [](const DeviceEntry& a, const DeviceEntry& b) {
        if (a.isGpu != b.isGpu) {
            return a.isGpu > b.isGpu;
        }
        if (a.isTranslationLayer != b.isTranslationLayer) {
            return a.isTranslationLayer < b.isTranslationLayer;
        }
        if (a.isDiscreteGpu != b.isDiscreteGpu) {
            return a.isDiscreteGpu > b.isDiscreteGpu;
        }
        if (a.globalMemBytes != b.globalMemBytes) {
            return a.globalMemBytes > b.globalMemBytes;
        }
        return a.computeUnits > b.computeUnits;
    });
    return result;
}

/**
 * @brief Format the enumerated device list for error diagnostics.
 *
 * @param devices  Enumerated OpenCL devices.
 * @return         Comma-separated `[i] Name` summary.
 */
std::string formatDeviceList(const std::vector<DeviceEntry>& devices) {
    std::string out;
    for (std::size_t i = 0; i < devices.size(); ++i) {
        if (i > 0) {
            out += ", ";
        }
        out += std::format("[{}] {}", i, devices[i].name);
    }
    return out;
}

/**
 * @brief Resolve a user-supplied device selector (index or substring) into a device index.
 *
 * @param devices   Non-empty list of enumerated OpenCL devices.
 * @param selector  Trimmed selector string (digits or name/vendor/platform substring).
 * @return          Zero-based index into `devices`, or `ErrorCode::InvalidArgument`.
 */
Result<int> resolveDeviceSelector(const std::vector<DeviceEntry>& devices, std::string_view selector) {
    const std::string_view clean = trimAscii(selector);
    if (clean.empty()) {
        return 0;
    }
    // Check whether the selector is a pure non-negative integer index.
    bool allDigits = true;
    for (const char c : clean) {
        if (!std::isdigit(static_cast<unsigned char>(c))) {
            allDigits = false;
            break;
        }
    }
    if (allDigits) {
        try {
            const int idx = std::stoi(std::string(clean));
            if (idx >= 0 && idx < static_cast<int>(devices.size())) {
                return idx;
            }
        } catch (...) {
            // Fall through to the out-of-range error below.
        }
        return Error{ErrorCode::InvalidArgument,
                     std::format("OpenCL device index '{}' out of range (0..{}); available: {}", clean,
                                 devices.size() - 1, formatDeviceList(devices))};
    }
    // Substring match against device name, vendor, or platform name.
    for (std::size_t i = 0; i < devices.size(); ++i) {
        if (containsIgnoreCase(devices[i].name, clean) || containsIgnoreCase(devices[i].vendor, clean) ||
            containsIgnoreCase(devices[i].platformName, clean)) {
            return static_cast<int>(i);
        }
    }
    return Error{ErrorCode::InvalidArgument,
                 std::format("no OpenCL device matching '{}'; available: {}", clean, formatDeviceList(devices))};
}

/// A device buffer that only grows.
struct ClBuffer {
    cl_mem mem = nullptr;
    std::size_t bytes = 0;

    Status ensure(cl_context ctx, std::size_t needed, cl_mem_flags flags) {
        if (mem && needed <= bytes) {
            return okStatus();
        }
        release();
        cl_int err = CL_SUCCESS;
        mem = clCreateBuffer(ctx, flags, needed, nullptr, &err);
        if (err != CL_SUCCESS || !mem) {
            mem = nullptr;
            return failStatus(ErrorCode::Gpu, clMessage("clCreateBuffer", err));
        }
        bytes = needed;
        return okStatus();
    }

    void release() noexcept {
        if (mem) {
            clReleaseMemObject(mem);
            mem = nullptr;
        }
        bytes = 0;
    }
};

